//! Builds RESULTS.md from the JSON/markdown files in the results directory.
//! Every number in the report comes from those files, nothing is hardcoded.

use crate::data::Data;
use serde_json::Value;
use std::collections::HashMap;
use std::fmt::Write;
use std::path::Path;

fn rd(out: &Path, name: &str) -> Option<Value> {
    std::fs::read_to_string(out.join(name)).ok().and_then(|s| serde_json::from_str(&s).ok())
}

fn pct(v: &Value) -> String {
    v.as_f64().map(|x| format!("{:.2}%", 100.0 * x)).unwrap_or("-".into())
}

fn key(v: &Value) -> (u64, u64) {
    if v["feasible"].as_bool() == Some(false) {
        return (u64::MAX, u64::MAX);
    }
    let late = v["late_answers"].as_u64().unwrap_or(0);
    let total = v["total_guesses"].as_u64().unwrap_or(u64::MAX);
    if v["mode"] == "Le4" { (late, total) } else { (total, 0) }
}

fn dist_row(label: &str, v: &Value) -> String {
    let d = &v["dist"];
    let s = &d["solved_in"];
    format!(
        "| {} | {} | {} | {} | {} | {} | {} | {} | {} | {:.4} | {} | {} | {} |\n",
        label, d["n"], s["1"], s["2"], s["3"], s["4"], s["5"], s["6"], d["fail"],
        d["avg"].as_f64().unwrap_or(0.0), pct(&d["p_le3"]), pct(&d["p_le4"]), pct(&d["p_3or4"])
    )
}

const DIST_HDR: &str = "| strategy | N | 1 | 2 | 3 | 4 | 5 | 6 | fail | avg | <=3 | <=4 | 3 or 4 |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|\n";

/// Spearman rank correlation.
fn spearman(a: &[f64], b: &[f64]) -> f64 {
    fn ranks(x: &[f64]) -> Vec<f64> {
        let mut idx: Vec<usize> = (0..x.len()).collect();
        idx.sort_by(|&i, &j| x[i].total_cmp(&x[j]));
        let mut r = vec![0.0; x.len()];
        let mut i = 0;
        while i < idx.len() {
            let mut j = i;
            while j + 1 < idx.len() && x[idx[j + 1]] == x[idx[i]] {
                j += 1;
            }
            for k in i..=j {
                r[idx[k]] = (i + j) as f64 / 2.0;
            }
            i = j + 1;
        }
        r
    }
    let (ra, rb) = (ranks(a), ranks(b));
    let n = a.len() as f64;
    let (ma, mb) = (ra.iter().sum::<f64>() / n, rb.iter().sum::<f64>() / n);
    let (mut c, mut va, mut vb) = (0.0, 0.0, 0.0);
    for i in 0..a.len() {
        c += (ra[i] - ma) * (rb[i] - mb);
        va += (ra[i] - ma).powi(2);
        vb += (rb[i] - mb).powi(2);
    }
    c / (va.sqrt() * vb.sqrt())
}

/// All shortlist files for a universe and mode, ordered from smallest beam to exact.
fn shortlists(out: &Path, universe: &str, mode: &str) -> Vec<(String, usize, Vec<Value>)> {
    let mut v = Vec::new();
    if let Ok(rd_) = std::fs::read_dir(out) {
        for e in rd_.flatten() {
            let name = e.file_name().to_string_lossy().to_string();
            let pre = format!("shortlist_{universe}_{mode}_");
            if let Some(rest) = name.strip_prefix(&pre) {
                let tag = rest.trim_end_matches(".json");
                let beam = if tag == "exact" { usize::MAX } else { tag.trim_start_matches('b').parse().unwrap_or(0) };
                if let Some(Value::Array(rows)) = rd(out, &name) {
                    v.push((tag.to_string(), beam, rows));
                }
            }
        }
    }
    v.sort_by_key(|x| x.1);
    v
}

pub fn build(out: &Path, d: &Data) -> String {
    let mut md = String::new();
    let threads = std::thread::available_parallelism().map(|n| n.get()).unwrap_or(1);
    let _ = writeln!(md, "# Wordle opener optimization: results\n");
    let _ = writeln!(md, "Generated by `wordle-opt report`. Every number below was computed by this program from the files in `results/`.\n");

    // ---------- Final recommendation ----------
    let _ = writeln!(md, "## Final recommendation\n");
    let best_tree = rd(out, "tree_full_expected.json");
    let best_le4 = rd(out, "tree_full_le4.json");
    let best_hard = rd(out, "tree_full_expected-hard.json");
    let pairtrees = ["exact", "b100", "b30"]
        .iter()
        .find_map(|t| rd(out, &format!("pairtrees_full_expected_{t}.json")).map(|v| (t.to_string(), v)));
    if let Some(t) = &best_tree {
        let s = &t["summary"];
        let _ = writeln!(md, "- **Best first word (adaptive, min average guesses):** `{}` ({}), avg {:.4}, solved in 3 or 4: {}, failures: {}",
            s["first"].as_str().unwrap_or("?").to_uppercase(),
            if s["exact"] == true { "exact search" } else { "beam search" },
            s["dist"]["avg"].as_f64().unwrap_or(0.0), pct(&s["dist"]["p_3or4"]), s["dist"]["fail"]);
    }
    if let Some(t) = &best_le4 {
        let s = &t["summary"];
        let _ = writeln!(md, "- **Best first word for P(solved <= 4):** `{}`, solved <= 4: {}, avg {:.4}, failures: {}",
            s["first"].as_str().unwrap_or("?").to_uppercase(), pct(&s["dist"]["p_le4"]),
            s["dist"]["avg"].as_f64().unwrap_or(0.0), s["dist"]["fail"]);
    }
    if let Some(t) = &best_hard {
        let s = &t["summary"];
        let _ = writeln!(md, "- **Best first word in HARD mode:** `{}`, avg {:.4}, solved in 3 or 4: {}, failures: {}",
            s["first"].as_str().unwrap_or("?").to_uppercase(), s["dist"]["avg"].as_f64().unwrap_or(0.0),
            pct(&s["dist"]["p_3or4"]), s["dist"]["fail"]);
    }
    if let Some((tag, Value::Array(rows))) = &pairtrees {
        let mut rows = rows.clone();
        rows.sort_by_key(key);
        if let Some(r) = rows.first() {
            let _ = writeln!(md, "- **Best fixed pair (same two words every game, then optimal play, {tag}):** `{}` + `{}`, avg {:.4}, solved in 3 or 4: {}, failures: {}",
                r["first"].as_str().unwrap().to_uppercase(), r["second"].as_str().unwrap().to_uppercase(),
                r["dist"]["avg"].as_f64().unwrap_or(0.0), pct(&r["dist"]["p_3or4"]), r["dist"]["fail"]);
        }
    }
    if let Some(p) = rd(out, "pairs_full.json") {
        if let Some(r) = p["top"].get(0) {
            let _ = writeln!(md, "- **Best fixed pair by partition (max P(solved <= 3)):** `{}` + `{}`, {} joint buckets, P(<=3) {}, P(<=4) with best 3rd guess {}",
                r["first"].as_str().unwrap().to_uppercase(), r["second"].as_str().unwrap().to_uppercase(),
                r["buckets"], pct(&r["p_le3"]), pct(&r["p_le4_adaptive_third"]));
        }
    }
    let _ = writeln!(md);

    // ---------- Data ----------
    let n_hist = d.history.len();
    let mut seen = std::collections::HashSet::new();
    let mut repeats = 0;
    for (_, c) in &d.history {
        if !seen.insert(*c) {
            repeats += 1;
        }
    }
    let nyt: std::collections::HashSet<u16> = d.universe("nyt2309").into_iter().collect();
    let off = d.history.iter().filter(|h| !nyt.contains(&h.1)).count();
    let recent: Vec<_> = d.history.iter().rev().take(90).collect();
    let recent_off = recent.iter().filter(|h| !nyt.contains(&h.1)).count();
    let _ = writeln!(md, "## Data and answer universes\n");
    let _ = writeln!(md, "See `data/README.md` for sources and fetch dates.\n");
    let _ = writeln!(md, "| list | words |\n|---|---|");
    let _ = writeln!(md, "| allowed guesses | {} |", d.guesses.len());
    for u in ["full", "nyt2309", "unused", "historical"] {
        let _ = writeln!(md, "| universe `{u}` | {} |", d.universe(u).len());
    }
    let _ = writeln!(md, "| history (games, {} to {}) | {} |\n", d.history.first().map(|h| h.0.as_str()).unwrap_or("?"),
        d.history.last().map(|h| h.0.as_str()).unwrap_or("?"), n_hist);
    let _ = writeln!(md, "- Repeated answers in history: **{repeats}** (NYT allows repeats since Feb 2026).");
    let _ = writeln!(md, "- Answers outside NYT's original curated list: **{off}** overall, **{recent_off} of the last 90** games.");
    let _ = writeln!(md, "- So `unused` is no longer \"the future\": future answers include repeats and brand new words. `full` (curated list plus every word NYT actually used) is the most realistic target and is the primary universe below. `historical` is the backtest.\n");

    // ---------- First words ----------
    let _ = writeln!(md, "## First word rankings (cheap metrics)\n");
    if let Ok(t) = std::fs::read_to_string(out.join("rank_first_full.md")) {
        md.push_str(&t);
    }
    for u in ["unused", "historical", "nyt2309"] {
        if let Ok(t) = std::fs::read_to_string(out.join(format!("rank_first_{u}.md"))) {
            let _ = writeln!(md, "\n<details><summary>Universe `{u}`</summary>\n{t}\n</details>\n");
        }
    }

    // ---------- Fixed pairs ----------
    let _ = writeln!(md, "\n## Fixed first + second pairs\n");
    if let Ok(t) = std::fs::read_to_string(out.join("pairs_full.md")) {
        md.push_str(&t);
    }
    if let Some((tag, Value::Array(rows))) = &pairtrees {
        let mut rows = rows.clone();
        rows.sort_by_key(key);
        let _ = writeln!(md, "\n### Top fixed pairs played out with optimal play from guess 3 ({tag})\n\n{DIST_HDR}");
        for r in &rows {
            md.push_str(&dist_row(&format!("{} + {}", r["first"].as_str().unwrap(), r["second"].as_str().unwrap()), r));
        }
    }
    for u in ["unused", "historical"] {
        if let Ok(t) = std::fs::read_to_string(out.join(format!("pairs_{u}.md"))) {
            let _ = writeln!(md, "\n<details><summary>Pairs, universe `{u}`</summary>\n{t}\n</details>\n");
        }
    }

    // ---------- Tree search ----------
    let _ = writeln!(md, "\n## Game-tree search (adaptive second guess)\n");
    let _ = writeln!(md, "`exact` = every allowed guess considered at every node (no heuristic cut). `bK` = big nodes only consider the top K guesses by expected remaining size; nodes with <= 12 candidates are always exhaustive.\n");
    let ranks: Option<HashMap<String, (f64, f64, f64)>> = rd(out, "rank_first_full.json").map(|v| {
        v["all"].as_array().unwrap().iter().map(|s| {
            (s["word"].as_str().unwrap().to_string(),
             (s["entropy"].as_f64().unwrap(), s["exp_size"].as_f64().unwrap(), s["buckets"].as_f64().unwrap()))
        }).collect()
    });
    for mode in ["expected", "le4", "expected-hard"] {
        let sl = shortlists(out, "full", mode);
        if sl.is_empty() {
            continue;
        }
        let _ = writeln!(md, "\n### Objective: {}\n", match mode { "expected" => "minimize average guesses", "le4" => "maximize P(solved <= 4), then average", _ => "HARD MODE, minimize average guesses" });
        for (tag, _, rows) in &sl {
            let mut rows = rows.clone();
            rows.sort_by_key(key);
            let _ = writeln!(md, "\n**Shortlist, {tag}** ({} openers)\n\n{DIST_HDR}", rows.len());
            for r in rows.iter().take(25) {
                md.push_str(&dist_row(r["first"].as_str().unwrap(), r));
            }
            // Does the cheap ranking predict the tree result?
            if let Some(rk) = &ranks {
                if rows.len() >= 5 {
                    let cost: Vec<f64> = rows.iter().map(|r| r["dist"]["avg"].as_f64().unwrap()).collect();
                    let get = |i: usize| -> Vec<f64> {
                        rows.iter().map(|r| {
                            let t = rk[r["first"].as_str().unwrap()];
                            match i { 0 => -t.0, 1 => t.1, _ => -t.2 }
                        }).collect()
                    };
                    let _ = writeln!(md, "\nSpearman correlation of tree average with cheap metric (1.0 = perfect agreement): entropy {:.2}, expected size {:.2}, buckets {:.2}\n",
                        spearman(&get(0), &cost), spearman(&get(1), &cost), spearman(&get(2), &cost));
                }
            }
        }
        // Convergence: same opener across beams.
        if sl.len() > 1 {
            let _ = writeln!(md, "\n**Beam convergence** (average guesses; if the numbers stop changing, wider search would not help)\n");
            let mut hdr = "| opener |".to_string();
            let mut sep = "|---|".to_string();
            for (tag, _, _) in &sl {
                hdr.push_str(&format!(" {tag} |"));
                sep.push_str("---|");
            }
            let _ = writeln!(md, "{hdr}\n{sep}");
            let last = &sl.last().unwrap().2;
            for r in last {
                let w = r["first"].as_str().unwrap();
                let mut line = format!("| {w} |");
                for (_, _, rows) in &sl {
                    let cell = rows.iter().find(|x| x["first"] == w)
                        .map(|x| format!("{:.4}", x["dist"]["avg"].as_f64().unwrap())).unwrap_or("-".into());
                    line.push_str(&format!(" {cell} |"));
                }
                let _ = writeln!(md, "{line}");
            }
        }
    }

    // ---------- Adaptive tree ----------
    if let Some(t) = &best_tree {
        let s = &t["summary"];
        let _ = writeln!(md, "\n## Adaptive tree for `{}`\n", s["first"].as_str().unwrap().to_uppercase());
        let _ = writeln!(md, "Full tree: `results/tree_full_expected.json`. Best second guess for each first-guess feedback (G = green, Y = yellow, . = gray), largest groups first:\n");
        let _ = writeln!(md, "| feedback | answers left | best 2nd guess |\n|---|---|---|");
        if let Some(obj) = s["second_by_pattern"].as_object() {
            let mut v: Vec<_> = obj.iter().collect();
            v.sort_by_key(|(_, x)| std::cmp::Reverse(x["n"].as_u64().unwrap_or(0)));
            for (p, x) in v {
                let _ = writeln!(md, "| `{p}` | {} | {} |", x["n"], x["second"].as_str().unwrap_or("-"));
            }
        }
    }

    // ---------- Validation ----------
    let _ = writeln!(md, "\n## Validation (simulating saved trees against every answer)\n\n{DIST_HDR}");
    if let Ok(rd_) = std::fs::read_dir(out) {
        let mut names: Vec<String> = rd_.flatten().map(|e| e.file_name().to_string_lossy().to_string())
            .filter(|n| n.starts_with("sim_")).collect();
        names.sort();
        for n in names {
            if let Some(v) = rd(out, &n) {
                let hv = if v["hard"] == true { format!(" (hard, {} rule violations)", v["hard_violations"]) } else { String::new() };
                md.push_str(&dist_row(&format!("{} vs {}{hv}", v["tree"].as_str().unwrap().trim_end_matches(".json"), v["against"].as_str().unwrap()), &v));
            }
        }
    }
    let _ = writeln!(md, "\n`history-seq` replays every daily game in order (repeats included). Each tree is also checked to never exceed 6 guesses.\n");

    // ---------- Runtime ----------
    let _ = writeln!(md, "\n## Runtime\n\nThreads available: {threads}. Times per run are in each JSON (`seconds`). Release build with fat LTO, `target-cpu=native`.\n");
    let _ = writeln!(md, "| run | opener | seconds | nodes |\n|---|---|---|---|");
    for mode in ["expected", "le4", "expected-hard"] {
        for (tag, _, rows) in shortlists(out, "full", mode) {
            for r in rows.iter().take(3) {
                let _ = writeln!(md, "| full {mode} {tag} | {} | {:.1} | {} |", r["first"].as_str().unwrap(),
                    r["seconds"].as_f64().unwrap_or(0.0), r["nodes"]);
            }
        }
    }
    md
}
